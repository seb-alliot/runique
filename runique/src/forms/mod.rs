/// Associates a form with its model's entity: the gate decides on it.
///
/// Generated by `model!{}`, `extend!{}` and `#[form(schema = …)]`; a form
/// written by hand has none.
///
/// ```rust,ignore
/// search!(@BlogForm => Title contains "rust")
/// BlogForm::objects.get(&db, id).await?
/// ```
///
/// A form written by hand has no entity, so it can't stand where one is
/// required:
///
/// ```compile_fail
/// use runique::auth::form::LoginAdmin;
/// use runique::forms::FormEntity;
/// fn needs_an_entity<F: FormEntity>() {}
/// needs_an_entity::<LoginAdmin>();
/// ```
///
/// The same call with a form that has one compiles:
///
/// ```
/// use runique::auth::form::UserModelForm;
/// use runique::forms::FormEntity;
/// fn needs_an_entity<F: FormEntity>() {}
/// needs_an_entity::<UserModelForm>();
/// ```
///
/// The entity must carry `ModelMeta`: a plain SeaORM entity is refused.
///
/// ```compile_fail
/// use runique::forms::FormEntity;
/// use sea_orm::entity::prelude::*;
///
/// #[derive(Clone, Debug, PartialEq, DeriveEntityModel)]
/// #[sea_orm(table_name = "plain")]
/// pub struct Model {
///     #[sea_orm(primary_key)]
///     pub id: i32,
/// }
/// #[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
/// pub enum Relation {}
/// impl ActiveModelBehavior for ActiveModel {}
///
/// struct Form;
/// impl FormEntity for Form {
///     type Entity = Entity;
/// }
/// ```
///
/// The same `impl` on an entity with `ModelMeta` compiles:
///
/// ```
/// use runique::forms::FormEntity;
///
/// struct Form;
/// impl FormEntity for Form {
///     type Entity = runique::auth::user::Entity;
/// }
/// ```
///
/// `#[form(schema = …)]` no longer takes `model = …`, the entity comes from
/// the schema:
///
/// ```compile_fail
/// use runique::prelude::*;
///
/// #[form(schema = runique_users, model = runique_users::Entity)]
/// pub struct AccountForm;
/// impl RuniqueForm for AccountForm {}
/// ```
///
/// Without that attribute it compiles, and carries the schema's entity:
///
/// ```
/// use runique::forms::FormEntity;
/// use runique::prelude::*;
///
/// #[form(schema = runique_users)]
/// pub struct AccountForm;
/// impl RuniqueForm for AccountForm {}
///
/// fn entity_of<F: FormEntity<Entity = E>, E>() {}
/// entity_of::<AccountForm, runique::auth::user::Entity>();
/// ```
pub trait FormEntity {
    type Entity: crate::auth::meta::ModelMeta;
}
