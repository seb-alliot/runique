use crate::backend::lang::visitor_lang;
use crate::entities::contribution;
use runique::axum::http::HeaderMap;
use runique::prelude::*;

pub fn contribution_type_choices() -> Vec<ChoiceOption> {
    vec![
        ChoiceOption::new("runique", "Contribution au framework Runique"),
        ChoiceOption::new("cours", "Proposition de cours"),
    ]
}

#[form(schema = contribution, fields = [contribution_type, title, content])]
pub struct ContributionForm;

#[async_trait]
impl RuniqueForm for ContributionForm {
    // Replaces the schema-generated `contribution_type` field with a proper
    // `ChoiceField` (labeled options) instead of the raw text/enum widget
    // `to_form_field()` would derive. Static choices, no request dependency —
    // `customize()` already runs right after `register_fields()` on every
    // construction path (`register_fields`, generated by `#[form]`), so this is always in
    // place before validation, including the very first GET render.
    fn customize(form: &mut Forms) {
        form.field(
            &ChoiceField::new("contribution_type")
                .label("Contribution type")
                .choices(contribution_type_choices()),
        );
    }
    async fn clean(&mut self) -> Result<(), StrMap> {
        let title = self.cleaned::<String>("title").unwrap_or_default();
        let content = self.cleaned::<String>("content").unwrap_or_default();
        let mut errors = StrMap::new();

        if title.len() < 3 {
            errors.insert(
                "title".to_string(),
                "The title must be at least 3 characters long.".to_string(),
            );
        }
        if content.len() < 10 {
            errors.insert(
                "content".to_string(),
                "The content must be at least 10 characters long.".to_string(),
            );
        }

        if errors.is_empty() {
            Ok(())
        } else {
            Err(errors)
        }
    }
}

impl ContributionForm {
    pub async fn save(
        &mut self,
        db: &ADb,
        user_pk: Pk,
    ) -> Result<crate::entities::contribution::Model, DbErr> {
        let new_contribution = crate::entities::contribution::ActiveModel {
            user_id: Set(user_pk),
            contribution_type: Set(self
                .cleaned::<String>("contribution_type")
                .unwrap_or_default()
                .parse::<crate::entities::contribution::ContributionType>()
                .unwrap_or_default()),
            title: Set(self.cleaned::<String>("title").unwrap_or_default()),
            content: Set(self.cleaned::<String>("content").unwrap_or_default()),
            ..Default::default()
        };
        new_contribution.insert(db).await
    }
}

impl ContributionForm {
    pub fn in_language(mut self, headers: &HeaderMap) -> Self {
        if visitor_lang(headers) == "fr" {
            self.forms_mut()
                .field_label("contribution_type", "Type de contribution")
                .field_label("title", "Titre")
                .field_label("content", "Contenu");
        }
        self
    }
}
